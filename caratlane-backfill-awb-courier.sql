--   • If that row is already type='dispatched' (dispatched through the app
--     normally), only awb and courier_partner are set — every other field
--     (recipient, address, dispatch weight, dispatched_at) is left exactly
--     as-is, via COALESCE, so nothing already-correct gets overwritten.
--   • If that row is still type='packed' (dispatched on paper, never
--     confirmed in the app), it's flipped to type='dispatched' too, with
--     dispatched_at defaulting to NOW() (the real timestamp isn't known —
--     flag this to whoever reviews later if exact timing matters), and
--     recipient/address/pincode/phone backfilled from the order record
--     and dispatch_weight from the pack-time chargeable/actual weight —
--     same defaults the app itself uses when dispatching.
-- orders.status is synced to 'dispatched' for the same 138 order IDs
-- (harmless no-op for any that are already there).
--
